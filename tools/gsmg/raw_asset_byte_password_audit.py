def _self_test_provenance_json_matches_site_assets():
    """doc/img/site_mirror/PROVENANCE.json's 6 accepted rows are checked
    against the actual committed files -- byte count and, via each row's
    `local` basename, the matching SITE_ASSETS entry's own pinned SHA-256
    -- so the committed provenance record cannot drift from what
    self_test() actually verifies elsewhere. Self-contained: no dependency
    on the external, uncommitted source mirror directory."""
    provenance_path = REPO_ROOT / "doc" / "img" / "site_mirror" / "PROVENANCE.json"
    provenance = json.loads(provenance_path.read_text())
    rows = provenance["accepted_rows"]
    assert len(rows) == 6, len(rows)

    expected_basenames = {
        "favicon_small.png", "logo_medium.png", "background-full.jpg",
        "front_bg_1920.svg", "front_bittrex.svg", "lato-regular-webfont.woff",
    }
    actual_basenames = {Path(row["local"]).name for row in rows}
    assert actual_basenames == expected_basenames, (
        actual_basenames, expected_basenames,
    )  # exact set, not just a count -- rejects a duplicated/substituted row

    site_by_basename = {Path(rel).name: (rel, sha) for rel, sha, _note in SITE_ASSETS}
    for row in rows:
        basename = Path(row["local"]).name
        assert basename in site_by_basename, f"{basename} not in SITE_ASSETS"
        rel_path, expected_sha256 = site_by_basename[basename]
        full_path = REPO_ROOT / rel_path
        raw = full_path.read_bytes()
        assert len(raw) == row["bytes"], (basename, len(raw), row["bytes"])
        assert hashlib.sha256(raw).hexdigest() == expected_sha256, basename


