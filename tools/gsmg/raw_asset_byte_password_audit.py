def resolve_creator_media():
    """Every (group, id) in Phase 248's frozen list, resolved against the
    two real export directories: (label, full_path, sha256, date) rows.
    Raises if an export directory or a referenced media file is missing --
    this audit's real run needs the actual bytes, same as every other
    Telegram-media-dependent script in this project."""
    export_dirs = {"solver": SOLVER_EXPORT_DIR, "support": SUPPORT_EXPORT_DIR}
    exports = {label: load_export(d) for label, d in export_dirs.items()}
    by_id = {
        label: {m["id"]: m for m in data["messages"] if isinstance(m, dict)}
        for label, data in exports.items()
    }

    rows = []
    for group, ids in EXPECTED_CREATOR_MEDIA_IDS.items():
        for mid in ids:
            message = by_id[group][mid]
            rel_media = media_path(message)
            full_path = export_dirs[group] / rel_media
            sha256 = hashlib.sha256(full_path.read_bytes()).hexdigest()
            rows.append((f"{group}/{mid}", full_path, sha256, message.get("date", "")))
    return rows


def core_creator_media():
    """Deduplicated (label, full_path, sha256) rows for the 76 unique
    payloads dated before CREATOR_MEDIA_DATE_CUTOFF. Keeps the
    earliest-dated record when the same payload hash appears more than
    once. Validates CANONICAL_PAYLOAD_SET_DIGEST here -- not only in
    self_test() -- so the normal --run path (full_manifest() -> run())
    cannot silently score a differently-composed corpus of the same size
    as though it were this pinned one."""
    rows = resolve_creator_media()
    precutoff = [r for r in rows if r[3] < CREATOR_MEDIA_DATE_CUTOFF]
    precutoff.sort(key=lambda r: r[3])
    seen = {}
    for label, full_path, sha256, date in precutoff:
        seen.setdefault(sha256, (label, full_path, sha256))
    resolved = list(seen.values())

    actual_digest = payload_set_digest(resolved)
    if actual_digest != CANONICAL_PAYLOAD_SET_DIGEST:
        raise ValueError(
            f"creator-media payload set digest mismatch "
            f"(expected {CANONICAL_PAYLOAD_SET_DIGEST}, got {actual_digest}) -- "
            "resolved Telegram media bytes no longer match this manifest's pin"
        )
    return resolved


def payload_set_digest(rows):
    """CANONICAL_PAYLOAD_SET_DIGEST's own computation, applied to any
    (label, path, sha256) row list -- content-only, order-independent."""
    ordered = sorted({sha256 for _, _, sha256 in rows})
    return hashlib.sha256("\n".join(ordered).encode()).hexdigest()


def load_site_manifest():
    """Resolve SITE_ASSETS against disk, asserting each pinned SHA-256."""
    resolved = []
    for rel_path, expected_sha256, note in SITE_ASSETS:
        full_path = REPO_ROOT / rel_path
        raw = full_path.read_bytes()
        actual_sha256 = hashlib.sha256(raw).hexdigest()
        if actual_sha256 != expected_sha256:
            raise ValueError(
                f"{rel_path}: pinned SHA-256 mismatch "
                f"(expected {expected_sha256}, got {actual_sha256}) -- "
                "file changed since this manifest was frozen"
            )
        resolved.append((rel_path, full_path, expected_sha256))
    return resolved


def full_manifest():
    """Class A (7 site assets) + Class B (76 unique pre-cutoff creator
    media): (label, Path, sha256) rows, asserted disjoint by content hash."""
    site = load_site_manifest()
    creator = core_creator_media()
    site_hashes = {sha for _, _, sha in site}
    creator_hashes = {sha for _, _, sha in creator}
    overlap = site_hashes & creator_hashes
    if overlap:
        raise ValueError(f"site/creator-media manifests overlap by content: {overlap}")
    return site + creator


def asset_forms(path: Path):
    """(form_kind, bytes) triples for one asset: literal, raw digest, hex digest."""
    raw = path.read_bytes()
    digest = hashlib.sha256(raw).digest()
    return [
        ("literal_file_bytes", raw),
        ("sha256_raw_bytes", digest),
        ("sha256_hex", digest.hex().encode()),
    ]


def run(blobs=None):
    active_blobs = TARGET_BLOBS if blobs is None else blobs
    manifest = full_manifest()

    materials_tested = 0
    effective_attempts = 0
    hits = []
    for label, full_path, _sha256 in manifest:
        for form_kind, material in asset_forms(full_path):
            materials_tested += 1
            for family_name, oracle_fn, variants, forms_per_config in ORACLE_FAMILIES:
                effective_attempts += len(variants) * len(active_blobs) * forms_per_config
                if family_name == "keywrap":
                    for tag, wrap_kind, kdf_label, key_len, unwrapped in oracle_fn(
                        material, kdf_variants=variants, blobs=active_blobs,
                    ):
                        hits.append({
                            "asset": label, "form": form_kind, "family": family_name,
                            "blob": tag, "kdf": f"{kdf_label}/aes{key_len * 8}/{wrap_kind}",
                            "plaintext_hex": unwrapped.hex(),
                        })
                else:
                    result = oracle_fn(material, kdf_variants=variants, blobs=active_blobs)
                    if result:
                        tag, body, kdf_label, key_len = result
                        hits.append({
                            "asset": label, "form": form_kind, "family": family_name,
                            "blob": tag, "kdf": f"{kdf_label}/aes{key_len * 8}",
                            "plaintext_hex": body.hex(),
                        })

    return {
        "candidate_count": len(manifest),
        "materials_tested": materials_tested,
        "blobs": tuple(active_blobs),
        "oracle_families": [name for name, _, _, _ in ORACLE_FAMILIES],
        "total_variant_configs": sum(len(v) for _, _, v, _ in ORACLE_FAMILIES),
        "effective_decrypt_attempts": effective_attempts,
        "hits": hits,
        "total_hits": len(hits),
    }


def self_test():
    # Class A
    site = load_site_manifest()
    assert len(site) == EXPECTED_SITE_ASSET_COUNT
    assert len({sha for _, _, sha in site}) == EXPECTED_SITE_ASSET_COUNT, "duplicate site asset"

    # Class B -- re-derive Phase 248's own figures independently, not just
    # assert them, so a future export change is caught.
    all_rows = resolve_creator_media()
    assert len(all_rows) == EXPECTED_TOTAL_RECORDS, len(all_rows)
    assert len({r[2] for r in all_rows}) == EXPECTED_UNIQUE_ALL_DATES, (
        len({r[2] for r in all_rows}), "Phase 248 recorded 83 unique payloads"
    )
    precutoff = [r for r in all_rows if r[3] < CREATOR_MEDIA_DATE_CUTOFF]
    assert len(precutoff) == EXPECTED_PRECUTOFF_RECORDS, len(precutoff)
    creator = core_creator_media()
    assert len(creator) == EXPECTED_PRECUTOFF_UNIQUE, len(creator)
    # Content-only pin: catches a same-size corpus with different bytes,
    # which the count assertions above cannot.
    actual_digest = payload_set_digest(creator)
    assert actual_digest == CANONICAL_PAYLOAD_SET_DIGEST, (
        actual_digest, CANONICAL_PAYLOAD_SET_DIGEST,
    )

    manifest = full_manifest()
    assert len(manifest) == EXPECTED_SITE_ASSET_COUNT + EXPECTED_PRECUTOFF_UNIQUE

    forms0 = asset_forms(manifest[0][1])
    assert len(forms0) == EXPECTED_FORMS_PER_CANDIDATE
    assert forms0[1][1] == hashlib.sha256(forms0[0][1]).digest()
    assert forms0[2][1] == hashlib.sha256(forms0[0][1]).digest().hex().encode()

    total_materials = sum(len(asset_forms(fp)) for _, fp, _ in manifest)
    assert total_materials == len(manifest) * EXPECTED_FORMS_PER_CANDIDATE

    assert len(CBC_KDF_VARIANTS) == 24, len(CBC_KDF_VARIANTS)
    total_configs = sum(len(v) for _, _, v, _ in ORACLE_FAMILIES)
    assert total_configs == 84, total_configs  # 24 CBC + 12 ECB + 36 stream + 12 keywrap
    assert tuple(TARGET_BLOBS) == ("P32TRAILING",)

    expected_effective = total_materials * (24 + 12 + 36 + 12 * KEYWRAP_FORMS_PER_CONFIG)
    report = run(blobs=TARGET_BLOBS)
    assert report["effective_decrypt_attempts"] == expected_effective, (
        report["effective_decrypt_attempts"], expected_effective,
    )

    _self_test_keywrap_hit_handling()
    _self_test_favicon_small_matches_wayback_hash()
