SEED_BASE = 0x52000AB
NULL_TRIALS = 20_000
PROMOTION_THRESHOLD = 0.005
BOARD_ITERS = 60_000
BOARD_RESTARTS = 30
BOARD_T0, BOARD_T1 = 20.0, 0.3


def is_prime(n: int) -> bool:
    if n < 2:
        return False
    i = 2
    while i * i <= n:
        if n % i == 0:
            return False
        i += 1
    return True


def nontrivial_factor_pairs(n: int):
    return [(w, n // w) for w in range(2, n) if n % w == 0 and w <= n // w]


def structural_check():
    total = len(DBBI) + len(FAED)
    return {
        "dbbi_length": len(DBBI),
        "faed_length": len(FAED),
        "spliced_length": total,
        "is_prime": is_prime(total),
        "nontrivial_factor_pairs": nontrivial_factor_pairs(total),
        "conclusion": (
            "no nontrivial rectangular transposition grid applies to the "
            "full spliced stream" if is_prime(total) else
            "a nontrivial rectangular grid does apply -- transposition "
            "reading of the full splice is not structurally excluded"
        ),
    }


def best_pair_fit(stream: str):
    rows = [(pair_loss(stream, pair), pair) for pair in PAIRS]
    best_loss = min(loss for loss, _pair in rows)
    ties = tuple(pair for loss, pair in rows if loss == best_loss)
    return best_loss, ties


def joint_fit_observed():
    spliced = DBBI + FAED
    spliced_rev = FAED + DBBI
    dbbi_loss, dbbi_pairs = best_pair_fit(DBBI)
    faed_loss, faed_pairs = best_pair_fit(FAED)
    spliced_loss, spliced_pairs = best_pair_fit(spliced)
    spliced_rev_loss, spliced_rev_pairs = best_pair_fit(spliced_rev)
    return {
        "dbbi_alone": {"loss": dbbi_loss, "best_pairs": ["".join(p) for p in dbbi_pairs]},
        "faed_alone": {"loss": faed_loss, "best_pairs": ["".join(p) for p in faed_pairs]},
        "spliced_dbbi_then_faed": {
            "loss": spliced_loss, "best_pairs": ["".join(p) for p in spliced_pairs],
        },
        "spliced_faed_then_dbbi": {
            "loss": spliced_rev_loss, "best_pairs": ["".join(p) for p in spliced_rev_pairs],
        },
    }


def null_population(kind: str, trials: int, seed: int):
    rng = random.Random(seed)
    values = []
    for trial in range(trials):
        if kind == "euler":
            dbbi_s = euler_surrogate(DBBI, rng)
            faed_s = euler_surrogate(FAED, rng)
            if trial < 3:
                assert_primary_preservation(DBBI, dbbi_s)
                assert_primary_preservation(FAED, faed_s)
        elif kind == "endpoint_shuffle":
            dbbi_s = endpoint_fixed_shuffle(DBBI, rng)
            faed_s = endpoint_fixed_shuffle(FAED, rng)
            if trial < 3:
                assert_sensitivity_preservation(DBBI, dbbi_s)
                assert_sensitivity_preservation(FAED, faed_s)
        else:
            raise ValueError(kind)
        spliced = dbbi_s + faed_s
        loss, _ = best_pair_fit(spliced)
        values.append(loss)
    return values


def summarize(values, observed):
    ordered = sorted(values)
    # Lower loss = better fit to the 0.067 English reference. A real splice
    # that is "more coherent than chance" should have unusually LOW loss.
    extreme = sum(value <= observed for value in values)
    return {
        "trials": len(values),
        "extreme_count": extreme,
        "empirical_p": (extreme + 1) / (len(values) + 1),
        "minimum": ordered[0],
        "median": ordered[len(ordered) // 2],
        "q05": ordered[int(0.05 * (len(ordered) - 1))],
        "maximum": ordered[-1],
    }


_QUAD_CACHE = None


def quad_table():
    global _QUAD_CACHE
    if _QUAD_CACHE is None:
        _QUAD_CACHE, _ = load_language_model()
    return _QUAD_CACHE


def anneal_best(token_slots, seed_parts, iters=BOARD_ITERS, restarts=BOARD_RESTARTS):
    quad = quad_table()
    best_score, best_key = -1e18, None
    for restart in range(restarts):
        seed = derive_seed(SEED_BASE, *seed_parts, restart)
        key, score = anneal_board(token_slots, quad, PCG32(seed), iters, BOARD_T0, BOARD_T1)
        if score > best_score:
            best_score, best_key = score, key
    return best_score, best_key


def board_decode(stream: str, pair: tuple[str, str], seed_parts):
    codes = segment_raw(stream, pair)
    if codes is None:
        return None
    slots = slot_codes(pair)
    code_to_slot = {code: index for index, code in enumerate(slots)}
    import numpy as np
    token_slots = np.array([code_to_slot[code] for code in codes], dtype=np.int64)
    score, key = anneal_best(token_slots, seed_parts)
    normalized = normalized_quadgram_score(score, len(codes))
    letters = "".join(LETTER_ALPHABET[i] for i in key[token_slots])
    return {
        "pair": "".join(pair),
        "token_count": len(codes),
        "raw_quadgram_score": score,
        "normalized_quadgram_score": normalized,
        "decoded_preview": letters[:120],
    }


def coherence_stage(fit_observed):
    dbbi_pair = tuple(fit_observed["dbbi_alone"]["best_pairs"][0])
    faed_pair = tuple(fit_observed["faed_alone"]["best_pairs"][0])
    spliced_pair = tuple(fit_observed["spliced_dbbi_then_faed"]["best_pairs"][0])
    spliced_rev_pair = tuple(fit_observed["spliced_faed_then_dbbi"]["best_pairs"][0])
    return {
        "dbbi_alone_at_own_best_pair": board_decode(DBBI, dbbi_pair, (1, ord(dbbi_pair[0]), ord(dbbi_pair[1]))),
        "faed_alone_at_own_best_pair": board_decode(FAED, faed_pair, (2, ord(faed_pair[0]), ord(faed_pair[1]))),
        "spliced_dbbi_then_faed_at_joint_best_pair": board_decode(
            DBBI + FAED, spliced_pair, (3, ord(spliced_pair[0]), ord(spliced_pair[1]))
        ),
        "spliced_faed_then_dbbi_at_joint_best_pair": board_decode(
            FAED + DBBI, spliced_rev_pair, (4, ord(spliced_rev_pair[0]), ord(spliced_rev_pair[1]))
        ),
    }


def run(trials: int = NULL_TRIALS, run_stage3: bool = True):
    structural = structural_check()
    fit = joint_fit_observed()

    primary_null = null_population("euler", trials, SEED_BASE + 1)
    sensitivity_null = null_population("endpoint_shuffle", trials, SEED_BASE + 2)
    observed_loss = fit["spliced_dbbi_then_faed"]["loss"]
    primary_summary = summarize(primary_null, observed_loss)
    sensitivity_summary = summarize(sensitivity_null, observed_loss)

    passes = (
        primary_summary["empirical_p"] <= PROMOTION_THRESHOLD,
        sensitivity_summary["empirical_p"] <= PROMOTION_THRESHOLD,
    )
    if all(passes):
        decision = "robust_joint_coherence"
    elif any(passes):
        decision = "null_sensitive"
    else:
        decision = "no_calibrated_joint_coherence"

    result = {
        "phase": 520,
        "structural_check": structural,
        "code_ic_fit": fit,
        "nulls": {
            "primary_euler": primary_summary,
            "sensitivity_endpoint_shuffle": sensitivity_summary,
        },
        "promotion_threshold": PROMOTION_THRESHOLD,
        "decision": decision,
        "stage3_run": False,
        "maximum_inference": "corroboration_only_no_gap_closure_no_matrixsumlist_reading_selected",
        "password_materials_generated": 0,
        "oracle_calls": 0,
    }

    if run_stage3:
        result["coherence_check"] = coherence_stage(fit)
        result["stage3_run"] = True

    return result


def self_test():
    assert is_prime(661) and not nontrivial_factor_pairs(661)
    assert not is_prime(91) and (7, 13) in nontrivial_factor_pairs(91)

    # code_ic/segment_codes reproduce known standing best pairs.
    dbbi_loss, dbbi_pairs = best_pair_fit(DBBI)
    faed_loss, faed_pairs = best_pair_fit(FAED)
    assert ("b", "e") in dbbi_pairs, dbbi_pairs
    assert ("g", "i") in faed_pairs, faed_pairs

    # Determinism.
    rng = random.Random(99)
    assert euler_surrogate(DBBI, random.Random(99)) == euler_surrogate(DBBI, rng)

    # Small null population sanity: values are all valid losses.
    values = null_population("euler", 5, SEED_BASE + 999)
    assert all(0.0 <= v <= INVALID_LOSS for v in values)

    print("[*] Phase 520 self-test OK: 661 confirmed prime with no nontrivial "
          "factor pairs, standing best pairs reproduced, null generator "
          "determinism and range checks passed")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--self-test", action="store_true")
    parser.add_argument("--run", action="store_true")
    parser.add_argument("--trials", type=int, default=NULL_TRIALS)
    parser.add_argument("--no-stage3", action="store_true")
    parser.add_argument("--json-out", type=Path, default=SCRIPT_DIR / "phase520_result.json")
    args = parser.parse_args()
    if args.self_test:
        self_test()
    elif args.run:
        start = time.monotonic()
        result = run(trials=args.trials, run_stage3=not args.no_stage3)
        elapsed = time.monotonic() - start
        result["elapsed_seconds"] = elapsed
        args.json_out.write_text(json.dumps(result, indent=2) + "\n", encoding="utf-8")
        print(f"[*] wrote {args.json_out} in {elapsed:.1f}s")
        print(f"[*] structural: {result['structural_check']['conclusion']}")
        print(f"[*] decision: {result['decision']}")
    else:
        self_test()


if __name__ == "__main__":
    main()
