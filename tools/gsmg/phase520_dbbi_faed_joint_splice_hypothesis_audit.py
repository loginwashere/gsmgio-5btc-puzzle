#!/usr/bin/env python3
"""Phase 520: is DBBI+FAED one continuous spliced stream, not two streams?

Motivating question (user-proposed, 2026-09-17): DBBI and FAED are
confirmed (Phase 101/243-244) to share one text node with no markup
boundary, joined only by the `matrixsumlist` instruction span --
structurally identical to a PEM/base64 blob whose payload is broken by an
inline marker. Has anyone tested treating `matrixsumlist` purely as a
splice marker (not a real instruction) and decoding `DBBI + FAED` as ONE
continuous 661-symbol raw checkerboard stream, the way you would strip a
PEM header/footer and rejoin the base64 lines before decoding?

This is distinct from every prior cross-stream test:
  - Phase 412 compared shared-vs-independent statistical PARAMETERS
    (unigram/Markov), not a literal joint decode attempt.
  - Phase 371 checked whether either adjacent instruction EMBEDS the
    other stream's content, not whether the streams themselves splice.
  - Phase 518 tested positional correspondence at proportional block
    granularity, not literal-concatenation decodability.

Three checks, cheapest first:

  1. STRUCTURAL: len(DBBI)+len(FAED) = 661. Is 661 prime? If so, no
     nontrivial rectangular transposition grid applies to the spliced
     stream under this project's own established width-admissibility
     convention (the same convention used for DBBI=7x13 and every one
     of FAED's admitted divisor pairs) -- this alone excludes a
     single-transposition-grid reading of the full splice, independent
     of any password oracle or board search.
  2. CODE-IC JOINT-FIT GATE: for each of the 36 escape pairs, the
     concatenation's own single best code-IC fit to the 0.067 English
     reference, calibrated against matched nulls that concatenate
     INDEPENDENTLY surrogate-generated DBBI/FAED (reusing Phase 459/460's
     validated Euler-traversal and endpoint-fixed-shuffle null
     generators) -- does the real splice fit one pair distinctly better
     than chance splices of two unrelated streams would?
  3. BOARD-ANNEAL COHERENCE (only run if gate 2 does not already look
     decisively negative): substitution-only decode (no transposition,
     per the structural finding in 1) of the spliced stream at its own
     single best pair, scored by the same quadgram solver validated in
     Phase 516, compared against each stream's own already-established
     best-pair decode at a matched budget.

No plaintext, password, or key material is generated by this script; no
AES oracle. Any positive result is corroboration_only and cannot itself
select a `matrixsumlist` reading or reopen/close `G-YIN-001`/`G-MSL-001`.
"""

